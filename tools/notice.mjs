// Each distinct licence text once, with the crates that use it. Texts that differ only in their
// copyright lines (which each crate's entry lists) count as one.
class Texts {
  constructor() {
    this.byKey = new Map();
  }

  add(licence, body, user) {
    // Without the copyright lines, which each crate's entry lists, and without a title line.
    const kept = body
      .split(/\r?\n/)
      .filter((line) => copyrightLines(line).length === 0)
      .join("\n")
      .replace(/^\s*(the )?mit license( \(mit\))?\s*\n/i, "")
      .replace(/\n\s*\n(\s*\n)+/g, "\n\n")
      .replace(/^\s*\n/, "")
      .trimEnd();
    const key = kept.toLowerCase().replace(/[\s*#/-]+/g, " ").trim();
    const entry = this.byKey.get(key) ?? { licences: [], text: kept, users: [] };
    if (!entry.licences.includes(licence)) entry.licences.push(licence);
    if (!entry.users.includes(user)) entry.users.push(user);
    this.byKey.set(key, entry);
  }

  render() {
    const parts = [
      "Apache-2.0: the Apache License, Version 2.0, whose text is in LICENSE, covers every crate used\nunder Apache-2.0 above.",
    ];
    const order = (entry) => Math.min(...entry.licences.map((id) => PREFERENCE.indexOf(id)));
    const entries = [...this.byKey.values()].sort(
      (a, b) => order(a) - order(b) || compareText(a.users[0], b.users[0]),
    );
    for (const { licences, text, users } of entries) {
      const names = licences.sort((a, b) => PREFERENCE.indexOf(a) - PREFERENCE.indexOf(b)).join(", ");
      parts.push(`----- ${names}: the text for ${users.join(", ")}\n\n${indent(text)}`);
    }
    return parts.join("\n\n");
  }
}

// Helpers ------------------------------------------------------------------------------------

function rule(title) {
  return `${"=".repeat(100)}\n${title}\n${"=".repeat(100)}`;
}

function indent(text, prefix = "  ") {
  return text
    .split("\n")
    .map((line) => (line.trim() === "" ? "" : `${prefix}${line.replace(/\s+$/, "")}`))
    .join("\n");
}

function namesHolder(line) {
  return /[a-z]{3,}/i.test(line.replace(/copyright|\(c\)|all rights reserved/gi, ""));
}

// The same statement once, however its files write the copyright sign.
function uniqueStatements(lines) {
  const seen = new Set();
  return lines.filter((line) => {
    const key = line.toLowerCase().replace(/\(c\)|©|[,.]/g, "").replace(/\s+/g, " ").trim();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function stripEmail(text) {
  return text
    .replace(/\s*[<(][^<>()\s]+@[^<>()\s]+[>)]/g, "")
    .replace(/\s*<[^>]*>/g, "")
    .replace(/\s*\S+@\S+\.[a-z]{2,}/gi, "")
    .trim();
}

// Words of `text` in lines of at most 100 characters, each after `prefix`.
function wrap(text, prefix) {
  const lines = [];
  let line = prefix;
  for (const word of text.split(" ")) {
    if (line.length > prefix.length && line.length + 1 + word.length > 100) {
      lines.push(line);
      line = `${prefix}  ${word}`;
    } else {
      line = line.length > prefix.length ? `${line} ${word}` : `${line}${word}`;
    }
  }
  lines.push(line);
  return lines.join("\n");
}

function unique(list) {
  return [...new Set(list)];
}

function fail(message) {
  console.error(`notice: ${message}`);
  process.exit(1);
}

main();
